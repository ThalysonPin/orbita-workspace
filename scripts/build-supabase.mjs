import { build } from "esbuild";
import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
const project = fileURLToPath(new URL("../", import.meta.url));
const directory = `${project}supabase/functions/orbita-api`;
await mkdir(directory, { recursive: true });
await build({ entryPoints: [`${directory}/service.ts`], outfile: `${directory}/bundle.mjs`, bundle: true, format: "esm", platform: "browser", target: "es2022", minify: false, sourcemap: false, legalComments: "none", treeShaking: true });
await writeFile(`${directory}/index.ts`, '// Generated by scripts/build-supabase.mjs. Do not edit.\nimport { createOrbitaHandler } from "./bundle.mjs";\nDeno.serve(createOrbitaHandler(Deno.env.toObject()));\n');
console.log("Supabase Edge bundle preparado; nenhuma implantação executada.");
